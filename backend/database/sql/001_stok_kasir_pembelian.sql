-- =====================================================================
-- Skema modul Stok Barang, Kasir/POS, serta Pembelian & Barang Masuk
-- Jalankan sekali di DBeaver (database Supabase "postgres", schema public).
-- Seluruh skrip dibungkus satu transaksi: jika ada yang gagal, tidak ada yang tersimpan.
--
-- Konvensi:
--   * Uang dalam rupiah bulat (BIGINT), tanpa float (PRD NFR-03).
--   * Waktu memakai TIMESTAMP tanpa zona, sama dengan tabel yang sudah ada.
--   * Nama & harga barang disalin ke baris item (snapshot), supaya struk/faktur lama
--     tidak berubah saat data barang diedit (PRD §9).
--   * Stok tidak boleh negatif (BR-06). Setiap perubahan stok dicatat di stock_movements.
--   * Transaksi tidak dihapus; dibatalkan lewat cancelled_at + alasan (BR-07).
--
-- Hak akses (keputusan tim, 4 Nov 2026): kasir = admin untuk Kasir & Stok;
-- Pembelian khusus admin. Pembatasan ini ada di route Laravel, bukan di database.
-- =====================================================================

BEGIN;

-- ---------------------------------------------------------------------
-- STOK BARANG
-- ---------------------------------------------------------------------

CREATE TABLE categories (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name        VARCHAR(50) NOT NULL,
    created_at  TIMESTAMP,
    updated_at  TIMESTAMP,
    CONSTRAINT categories_name_key UNIQUE (name)
);

CREATE TABLE products (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sku          VARCHAR(30),
    name         VARCHAR(120) NOT NULL,
    description  VARCHAR(300),
    category_id  BIGINT NOT NULL REFERENCES categories (id) ON DELETE RESTRICT,
    unit         VARCHAR(30) NOT NULL DEFAULT 'pcs',      -- satuan, mis. "pcs", "karung 5 kg"
    image_path   TEXT,
    buy_price    BIGINT NOT NULL DEFAULT 0 CHECK (buy_price >= 0),
    sell_price   BIGINT NOT NULL DEFAULT 0 CHECK (sell_price >= 0),
    stock        INTEGER NOT NULL DEFAULT 0 CHECK (stock >= 0),
    min_stock    INTEGER NOT NULL DEFAULT 0 CHECK (min_stock >= 0),
    is_active    BOOLEAN NOT NULL DEFAULT TRUE,           -- barang lama dinonaktifkan, bukan dihapus
    created_at   TIMESTAMP,
    updated_at   TIMESTAMP,
    CONSTRAINT products_sku_key UNIQUE (sku)
);
CREATE INDEX products_category_id_idx ON products (category_id);
CREATE INDEX products_name_idx ON products (lower(name));

-- Mutasi stok: satu baris per perubahan, dari mana pun asalnya.
CREATE TABLE stock_movements (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id      BIGINT NOT NULL REFERENCES products (id) ON DELETE RESTRICT,
    type            VARCHAR(20) NOT NULL CHECK (type IN (
                        'initial',     -- stok awal saat barang dibuat
                        'adjustment',  -- koreksi manual di halaman Stok
                        'sale',        -- penjualan kasir (qty_change negatif)
                        'sale_edit',   -- edit item transaksi
                        'sale_cancel', -- pembatalan transaksi (stok kembali)
                        'purchase'     -- penerimaan barang dari supplier
                    )),
    qty_change      INTEGER NOT NULL CHECK (qty_change <> 0),
    stock_after     INTEGER NOT NULL CHECK (stock_after >= 0),
    reference_type  VARCHAR(30),   -- mis. 'sale', 'purchase_receipt'
    reference_id    BIGINT,
    note            VARCHAR(300),
    user_id         BIGINT REFERENCES users (id) ON DELETE SET NULL,
    created_at      TIMESTAMP NOT NULL DEFAULT now()
);
CREATE INDEX stock_movements_product_id_idx ON stock_movements (product_id, created_at DESC);
CREATE INDEX stock_movements_reference_idx ON stock_movements (reference_type, reference_id);

-- ---------------------------------------------------------------------
-- KASIR / POS
-- ---------------------------------------------------------------------

CREATE TABLE sales (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    invoice_no      VARCHAR(30) NOT NULL,                 -- mis. TRX-041126-042
    user_id         BIGINT REFERENCES users (id) ON DELETE SET NULL,      -- kasir yang melayani
    customer_id     BIGINT REFERENCES customers (id) ON DELETE SET NULL,  -- NULL = pelanggan umum
    customer_name   VARCHAR(80),                          -- snapshot nama untuk struk
    total           BIGINT NOT NULL CHECK (total >= 0),
    paid_amount     BIGINT NOT NULL DEFAULT 0 CHECK (paid_amount >= 0),
    cash_received   BIGINT NOT NULL DEFAULT 0 CHECK (cash_received >= 0),
    change_amount   BIGINT NOT NULL DEFAULT 0 CHECK (change_amount >= 0),
    payment_method  VARCHAR(10) NOT NULL CHECK (payment_method IN ('tunai', 'transfer')),
    payment_status  VARCHAR(12) NOT NULL CHECK (payment_status IN ('lunas', 'belum_lunas', 'batal')),
    print_doc       VARCHAR(10) NOT NULL DEFAULT 'receipt' CHECK (print_doc IN ('receipt', 'invoice', 'none')),
    print_size      VARCHAR(10),                          -- ukuran kertas yang dipilih (mis. 58mm, 80mm, A4, A5)
    cancelled_at    TIMESTAMP,
    cancelled_by    BIGINT REFERENCES users (id) ON DELETE SET NULL,
    cancel_reason   VARCHAR(300),
    created_at      TIMESTAMP,
    updated_at      TIMESTAMP,
    CONSTRAINT sales_invoice_no_key UNIQUE (invoice_no),
    CONSTRAINT sales_paid_not_over_total CHECK (paid_amount <= total),
    -- Belum lunas wajib punya pelanggan terdaftar (aturan halaman Kasir)
    CONSTRAINT sales_unpaid_needs_customer CHECK (payment_status <> 'belum_lunas' OR customer_id IS NOT NULL),
    CONSTRAINT sales_cancel_consistent CHECK ((payment_status = 'batal') = (cancelled_at IS NOT NULL))
);
CREATE INDEX sales_created_at_idx ON sales (created_at DESC);
CREATE INDEX sales_customer_id_idx ON sales (customer_id);
CREATE INDEX sales_payment_status_idx ON sales (payment_status);

CREATE TABLE sale_items (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sale_id       BIGINT NOT NULL REFERENCES sales (id) ON DELETE CASCADE,
    product_id    BIGINT NOT NULL REFERENCES products (id) ON DELETE RESTRICT,
    product_name  VARCHAR(120) NOT NULL,
    unit          VARCHAR(30),
    unit_price    BIGINT NOT NULL CHECK (unit_price >= 0),
    qty           INTEGER NOT NULL CHECK (qty > 0),
    subtotal      BIGINT NOT NULL CHECK (subtotal >= 0)
);
CREATE INDEX sale_items_sale_id_idx ON sale_items (sale_id);
CREATE INDEX sale_items_product_id_idx ON sale_items (product_id);

-- Pembayaran awal & pelunasan (cicilan) per transaksi
CREATE TABLE sale_payments (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sale_id     BIGINT NOT NULL REFERENCES sales (id) ON DELETE CASCADE,
    paid_at     TIMESTAMP NOT NULL,
    method      VARCHAR(10) NOT NULL CHECK (method IN ('tunai', 'transfer')),
    amount      BIGINT NOT NULL CHECK (amount > 0),
    note        VARCHAR(200),
    user_id     BIGINT REFERENCES users (id) ON DELETE SET NULL,
    created_at  TIMESTAMP NOT NULL DEFAULT now()
);
CREATE INDEX sale_payments_sale_id_idx ON sale_payments (sale_id);

-- Jejak audit per transaksi (tab riwayat di Edit Transaksi)
CREATE TABLE sale_histories (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sale_id     BIGINT NOT NULL REFERENCES sales (id) ON DELETE CASCADE,
    type        VARCHAR(10) NOT NULL CHECK (type IN ('edit', 'payment', 'cancel')),
    reason      VARCHAR(300),
    user_id     BIGINT REFERENCES users (id) ON DELETE SET NULL,
    created_at  TIMESTAMP NOT NULL DEFAULT now()
);
CREATE INDEX sale_histories_sale_id_idx ON sale_histories (sale_id);

-- ---------------------------------------------------------------------
-- PEMBELIAN & BARANG MASUK (khusus admin)
-- ---------------------------------------------------------------------

CREATE TABLE suppliers (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name        VARCHAR(120) NOT NULL,
    phone       VARCHAR(30),
    address     VARCHAR(200),
    created_at  TIMESTAMP,
    updated_at  TIMESTAMP
);

CREATE TABLE purchases (
    id                       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    purchase_no              VARCHAR(40) NOT NULL,         -- no. faktur supplier / INV-YYYYMMDD-0001
    supplier_id              BIGINT NOT NULL REFERENCES suppliers (id) ON DELETE RESTRICT,
    user_id                  BIGINT REFERENCES users (id) ON DELETE SET NULL,   -- pembuat
    purchase_date            DATE NOT NULL,
    due_date                 DATE,
    location                 VARCHAR(30) NOT NULL DEFAULT 'gudang_utama',       -- gudang_utama | toko | gudang_b
    status                   VARCHAR(20) NOT NULL DEFAULT 'belum_diterima'
                                 CHECK (status IN ('belum_diterima', 'diterima_sebagian', 'diterima')),
    subtotal                 BIGINT NOT NULL DEFAULT 0 CHECK (subtotal >= 0),   -- jumlah item
    additional_cost          BIGINT NOT NULL DEFAULT 0 CHECK (additional_cost >= 0),
    total                    BIGINT NOT NULL DEFAULT 0 CHECK (total >= 0),      -- subtotal + biaya tambahan
    estimated_next_delivery  DATE,
    notes                    VARCHAR(500),
    created_at               TIMESTAMP,
    updated_at               TIMESTAMP,
    CONSTRAINT purchases_purchase_no_key UNIQUE (purchase_no),
    CONSTRAINT purchases_total_consistent CHECK (total = subtotal + additional_cost)
);
CREATE INDEX purchases_supplier_id_idx ON purchases (supplier_id);
CREATE INDEX purchases_purchase_date_idx ON purchases (purchase_date DESC);
CREATE INDEX purchases_status_idx ON purchases (status);

CREATE TABLE purchase_items (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    purchase_id   BIGINT NOT NULL REFERENCES purchases (id) ON DELETE CASCADE,
    product_id    BIGINT NOT NULL REFERENCES products (id) ON DELETE RESTRICT,
    product_name  VARCHAR(120) NOT NULL,
    unit          VARCHAR(30),
    qty           INTEGER NOT NULL CHECK (qty > 0),
    qty_received  INTEGER NOT NULL DEFAULT 0 CHECK (qty_received >= 0),
    unit_price    BIGINT NOT NULL CHECK (unit_price >= 0),
    subtotal      BIGINT NOT NULL CHECK (subtotal >= 0),
    CONSTRAINT purchase_items_received_not_over CHECK (qty_received <= qty)
);
CREATE INDEX purchase_items_purchase_id_idx ON purchase_items (purchase_id);
CREATE INDEX purchase_items_product_id_idx ON purchase_items (product_id);

-- Pembayaran ke supplier (pembayaran awal = baris pertama). Sisa hutang = total - SUM(amount).
CREATE TABLE purchase_payments (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    purchase_id  BIGINT NOT NULL REFERENCES purchases (id) ON DELETE CASCADE,
    paid_at      DATE NOT NULL,
    method       VARCHAR(20) NOT NULL CHECK (method IN ('transfer_bank', 'tunai', 'cek')),
    amount       BIGINT NOT NULL CHECK (amount > 0),
    note         VARCHAR(200),
    user_id      BIGINT REFERENCES users (id) ON DELETE SET NULL,
    created_at   TIMESTAMP NOT NULL DEFAULT now()
);
CREATE INDEX purchase_payments_purchase_id_idx ON purchase_payments (purchase_id);

-- Barang masuk: satu baris per kedatangan (bisa bertahap). Stok bertambah saat baris ini dibuat.
CREATE TABLE purchase_receipts (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    purchase_id    BIGINT NOT NULL REFERENCES purchases (id) ON DELETE RESTRICT,
    receipt_no     VARCHAR(30) NOT NULL,                  -- mis. BM-018
    received_at    TIMESTAMP NOT NULL,
    received_by    BIGINT REFERENCES users (id) ON DELETE SET NULL,
    delivery_note  VARCHAR(60),                           -- no. surat jalan
    notes          VARCHAR(500),
    created_at     TIMESTAMP NOT NULL DEFAULT now(),
    CONSTRAINT purchase_receipts_receipt_no_key UNIQUE (receipt_no)
);
CREATE INDEX purchase_receipts_purchase_id_idx ON purchase_receipts (purchase_id);

CREATE TABLE purchase_receipt_items (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    receipt_id        BIGINT NOT NULL REFERENCES purchase_receipts (id) ON DELETE CASCADE,
    purchase_item_id  BIGINT NOT NULL REFERENCES purchase_items (id) ON DELETE RESTRICT,
    qty               INTEGER NOT NULL CHECK (qty > 0)
);
CREATE INDEX purchase_receipt_items_receipt_id_idx ON purchase_receipt_items (receipt_id);

