-- =====================================================================
-- Skema lengkap modul Keuangan (khusus admin)
--
-- AMAN DIJALANKAN BERULANG KALI (idempotent): bagian yang sudah ada dilewati.
--   * Database baru      -> semua tabel & kolom terbentuk
--   * Database lama      -> hanya bagian yang belum ada yang ditambahkan
-- Setiap perubahan skema Keuangan berikutnya ditambahkan ke file ini (jangan buat file baru),
-- dengan pola IF NOT EXISTS / ON CONFLICT / UPDATE ... WHERE supaya tetap aman dijalankan ulang.
--
-- Laporan keuangan menggabungkan tiga sumber kas:
--   * sale_payments      -> pemasukan penjualan & pelunasan piutang (otomatis dari Kasir)
--   * purchase_payments  -> pengeluaran pembelian barang (otomatis dari Pembelian)
--   * cash_entries       -> catatan kas manual dari tombol "Catat masuk / keluar"
--
-- Catatan manual punya dua tingkat, keduanya bisa ditambah admin dari modal Catat:
--   * category    = JENIS (tabel cash_types). Setiap jenis punya EFEK yang menentukan cara hitung laporan:
--                     keluar: biaya       -> kas berkurang & laba usaha berkurang   (mis. "Biaya operasional")
--                             bukan_biaya -> hanya kas berkurang                     (mis. "Pembelian barang")
--                     masuk : pemasukan   -> kas bertambah, bukan penjualan          (mis. "Pemasukan lain")
--                             modal       -> kas bertambah dari pemilik              (mis. "Prive masuk")
--   * subcategory = KATEGORI (tabel cash_categories), label rincian;
--                   hanya untuk "Biaya operasional" dan "Pemasukan lain"
--
-- Konvensi sama dengan 001: uang BIGINT rupiah bulat, waktu TIMESTAMP tanpa zona.
-- =====================================================================

BEGIN;

-- ── 1. Catatan kas manual ───────────────────────────────────────────────
CREATE TABLE IF NOT EXISTS cash_entries (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    type         VARCHAR(6) NOT NULL CHECK (type IN ('masuk', 'keluar')),
    category     VARCHAR(50) NOT NULL,                 -- jenis, mis. "Biaya operasional"
    amount       BIGINT NOT NULL CHECK (amount > 0),
    entry_date   DATE NOT NULL,                        -- tanggal transaksi kas (bukan tanggal input)
    method       VARCHAR(10) NOT NULL DEFAULT 'tunai' CHECK (method IN ('tunai', 'transfer', 'qris')),
    description  VARCHAR(300),
    user_id      BIGINT REFERENCES users (id) ON DELETE SET NULL,   -- admin yang mencatat
    created_at   TIMESTAMP,
    updated_at   TIMESTAMP
);
CREATE INDEX IF NOT EXISTS cash_entries_entry_date_idx ON cash_entries (entry_date);

-- ── 2. Hapus lunak ──────────────────────────────────────────────────────
-- Catatan yang dihapus tidak dibuang: ditandai deleted_at + siapa + alasan,
-- tidak lagi dihitung di laporan, tetapi jejaknya tetap ada.
ALTER TABLE cash_entries ADD COLUMN IF NOT EXISTS deleted_at    TIMESTAMP;
ALTER TABLE cash_entries ADD COLUMN IF NOT EXISTS deleted_by    BIGINT REFERENCES users (id) ON DELETE SET NULL;
ALTER TABLE cash_entries ADD COLUMN IF NOT EXISTS delete_reason VARCHAR(300);

-- ── 3. Jenis (bisa ditambah admin dari modal Catat) ─────────────────────
CREATE TABLE IF NOT EXISTS cash_types (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    direction        VARCHAR(6) NOT NULL CHECK (direction IN ('masuk', 'keluar')),
    name             VARCHAR(50) NOT NULL,
    effect           VARCHAR(12) NOT NULL,
    has_subcategory  BOOLEAN NOT NULL DEFAULT FALSE,     -- wajib pilih kategori (cash_categories)
    sort_order       SMALLINT NOT NULL DEFAULT 100,      -- bawaan diurutkan dulu, tambahan admin menurut abjad
    user_id          BIGINT REFERENCES users (id) ON DELETE SET NULL,   -- admin yang menambah (NULL = bawaan)
    created_at       TIMESTAMP,
    updated_at       TIMESTAMP,
    CONSTRAINT cash_types_effect_check CHECK (
        (direction = 'keluar' AND effect IN ('biaya', 'bukan_biaya'))
        OR (direction = 'masuk' AND effect IN ('pemasukan', 'modal'))
    )
);
CREATE UNIQUE INDEX IF NOT EXISTS cash_types_direction_name_key ON cash_types (direction, lower(name));

INSERT INTO cash_types (direction, name, effect, has_subcategory, sort_order, created_at, updated_at) VALUES
    ('keluar', 'Biaya operasional', 'biaya',       TRUE,  1, now(), now()),
    ('keluar', 'Pembelian barang',  'bukan_biaya', FALSE, 2, now(), now()),
    ('masuk',  'Pemasukan lain',    'pemasukan',   TRUE,  1, now(), now()),
    ('masuk',  'Prive masuk',       'modal',       FALSE, 2, now(), now())
ON CONFLICT (direction, lower(name)) DO NOTHING;

-- ── 4. Kategori (bisa ditambah admin dari modal Catat) ──────────────────
ALTER TABLE cash_entries ADD COLUMN IF NOT EXISTS subcategory VARCHAR(50);

CREATE TABLE IF NOT EXISTS cash_categories (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    parent      VARCHAR(50) NOT NULL CHECK (parent IN ('Biaya operasional', 'Pemasukan lain')),
    name        VARCHAR(50) NOT NULL,
    sort_order  SMALLINT NOT NULL DEFAULT 100,         -- bawaan diurutkan; "Lainnya" selalu terakhir
    user_id     BIGINT REFERENCES users (id) ON DELETE SET NULL,   -- admin yang menambah (NULL = bawaan)
    created_at  TIMESTAMP,
    updated_at  TIMESTAMP
);
-- Nama unik per jenis tanpa beda huruf besar/kecil ("Parkir" = "parkir")
CREATE UNIQUE INDEX IF NOT EXISTS cash_categories_parent_name_key ON cash_categories (parent, lower(name));

INSERT INTO cash_categories (parent, name, sort_order, created_at, updated_at) VALUES
    ('Biaya operasional', 'Gaji',              1,   now(), now()),
    ('Biaya operasional', 'Listrik & air',     2,   now(), now()),
    ('Biaya operasional', 'Sewa toko',         3,   now(), now()),
    ('Biaya operasional', 'Transportasi',      4,   now(), now()),
    ('Biaya operasional', 'Lainnya',           999, now(), now()),
    ('Pemasukan lain',    'Jual barang bekas', 1,   now(), now()),
    ('Pemasukan lain',    'Lainnya',           999, now(), now())
ON CONFLICT (parent, lower(name)) DO NOTHING;

-- Pindahkan catatan lama ke susunan jenis + kategori (hanya mengenai baris lama, aman diulang)
UPDATE cash_entries SET subcategory = category, category = 'Biaya operasional'
    WHERE type = 'keluar' AND category IN ('Gaji', 'Listrik & air', 'Sewa toko', 'Transportasi');
UPDATE cash_entries SET subcategory = 'Lainnya', category = 'Biaya operasional'
    WHERE type = 'keluar' AND category = 'Biaya lainnya';
UPDATE cash_entries SET category = 'Pemasukan lain'
    WHERE type = 'masuk' AND category = 'Lainnya';
UPDATE cash_entries SET subcategory = 'Lainnya'
    WHERE category IN ('Biaya operasional', 'Pemasukan lain') AND subcategory IS NULL;

COMMIT;
