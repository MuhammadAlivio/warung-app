-- =====================================================================
-- Skema modul Keuangan (khusus admin)
-- Jalankan sekali di DBeaver setelah 001_stok_kasir_pembelian.sql.
--
-- Laporan keuangan menggabungkan tiga sumber kas:
--   * sale_payments      -> pemasukan penjualan & pelunasan piutang (otomatis dari Kasir)
--   * purchase_payments  -> pengeluaran pembelian barang (otomatis dari Pembelian)
--   * cash_entries       -> catatan kas manual dari tombol "Catat masuk / keluar" (tabel baru ini)
--
-- Konvensi sama dengan 001: uang BIGINT rupiah bulat, waktu TIMESTAMP tanpa zona.
-- Kategori tidak dibatasi CHECK supaya daftar kategori bisa berkembang;
-- daftar yang valid dijaga di FinanceService (backend) dan financeMockData.js (frontend).
-- =====================================================================

BEGIN;

CREATE TABLE cash_entries (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    type         VARCHAR(6) NOT NULL CHECK (type IN ('masuk', 'keluar')),
    category     VARCHAR(50) NOT NULL,                 -- mis. "Gaji", "Listrik & air", "Prive pemilik"
    amount       BIGINT NOT NULL CHECK (amount > 0),
    entry_date   DATE NOT NULL,                        -- tanggal transaksi kas (bukan tanggal input)
    method       VARCHAR(10) NOT NULL DEFAULT 'tunai' CHECK (method IN ('tunai', 'transfer', 'qris')),
    description  VARCHAR(300),
    user_id      BIGINT REFERENCES users (id) ON DELETE SET NULL,   -- admin yang mencatat
    created_at   TIMESTAMP,
    updated_at   TIMESTAMP
);
CREATE INDEX cash_entries_entry_date_idx ON cash_entries (entry_date);

COMMIT;
