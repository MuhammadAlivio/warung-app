-- =====================================================================
-- Daftar lokasi penerimaan barang (modul Pembelian & Barang Masuk, khusus admin)
--
-- AMAN DIJALANKAN BERULANG KALI (idempotent): bagian yang sudah ada dilewati.
--
-- Sebelumnya lokasi ditulis tetap di kode (Gudang utama, Toko, Gudang B). Sekarang admin
-- bisa menambah, mengganti nama, dan menghapus lokasi dari form Buat Pembelian.
--
-- purchases.location tetap menyimpan KODE lokasi (mis. "gudang_utama"), bukan nama:
-- mengganti nama lokasi tidak mengubah faktur lama, dan kode tidak pernah berubah.
-- Lokasi yang masih dipakai faktur tidak bisa dihapus (dicek di backend).
--
-- Konvensi sama dengan 001: waktu TIMESTAMP tanpa zona.
-- =====================================================================

BEGIN;

CREATE TABLE IF NOT EXISTS purchase_locations (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code        VARCHAR(30) NOT NULL,                  -- dipakai purchases.location, tidak berubah
    name        VARCHAR(50) NOT NULL,                  -- nama tampilan, bisa diganti admin
    sort_order  SMALLINT NOT NULL DEFAULT 100,         -- bawaan diurutkan dulu, tambahan admin menurut abjad
    user_id     BIGINT REFERENCES users (id) ON DELETE SET NULL,   -- admin yang menambah (NULL = bawaan)
    created_at  TIMESTAMP,
    updated_at  TIMESTAMP,
    CONSTRAINT purchase_locations_code_key UNIQUE (code)
);
-- Nama unik tanpa beda huruf besar/kecil ("Toko" = "toko")
CREATE UNIQUE INDEX IF NOT EXISTS purchase_locations_name_key ON purchase_locations (lower(name));

INSERT INTO purchase_locations (code, name, sort_order, created_at, updated_at) VALUES
    ('gudang_utama', 'Gudang utama', 1, now(), now()),
    ('toko',         'Toko',         2, now(), now()),
    ('gudang_b',     'Gudang B',     3, now(), now())
ON CONFLICT (code) DO NOTHING;

-- Lokasi lain yang mungkin sudah tercatat di faktur lama ikut didaftarkan (nama = kode)
INSERT INTO purchase_locations (code, name, created_at, updated_at)
SELECT DISTINCT p.location, p.location, now(), now()
FROM purchases p
WHERE NOT EXISTS (SELECT 1 FROM purchase_locations l WHERE l.code = p.location)
ON CONFLICT DO NOTHING;

-- Nomor faktur sekarang opsional di form; jika kosong backend membuat PB-YYMMDD-NNN.
-- Kolom purchase_no tetap NOT NULL dan unik, jadi tidak ada perubahan di sini.

COMMIT;
